//! Lightweight localization system for ArchSwift.
//!
//! Translations live in `localization/lang/<lang>.toml`. At build time
//! `build.rs` scans that directory and generates the `CATALOGS` registry, and
//! file contents are embedded into the binary through `include_str!`. As a result:
//!   - a new language is one TOML file, with no Rust changes;
//!   - the application does not have to look for translations on disk.
//!
//! The language is chosen from environment variables in priority order:
//! `ARCHSWIFT_LANG`, `LANGUAGE`, `LC_ALL`, `LC_MESSAGES`, `LANG`.
//! If none of them yields a supported language, English is used. An unknown
//! `ARCHSWIFT_LANG` also yields English: it is an explicit override and must
//! not depend on the system locale.

use std::collections::HashMap;
use std::sync::OnceLock;

// The registry is generated by build.rs: &[(language code, TOML content)].
include!(concat!(env!("OUT_DIR"), "/languages.rs"));

/// Language used as a fallback for missing keys.
const FALLBACK_LANGUAGE: &str = "en";

struct Catalog {
    language: &'static str,
    messages: HashMap<String, String>,
    fallback: HashMap<String, String>,
}

impl Catalog {
    fn lookup<'a>(&'a self, key: &'a str) -> &'a str {
        self.messages
            .get(key)
            .or_else(|| self.fallback.get(key))
            .map(String::as_str)
            .unwrap_or(key)
    }
}

static CATALOG: OnceLock<Catalog> = OnceLock::new();

/// Code of the active language (`en`, `ru`, `be` or another from `localization/lang`).
pub fn language() -> &'static str {
    catalog().language
}

/// Returns the translation for a key and substitutes named `{name}` arguments.
///
/// If the key is missing in the selected language, the English variant is used.
/// If the key is missing there too, the key itself is returned — that is easy to
/// notice during development and never crashes the application.
pub fn tr(key: &str, args: &[(&str, &str)]) -> String {
    interpolate(catalog().lookup(key), args)
}

fn catalog() -> &'static Catalog {
    CATALOG.get_or_init(|| {
        let fallback = parse_catalog(source(FALLBACK_LANGUAGE)).unwrap_or_else(|error| {
            eprintln!(
                "[ArchSwift] Failed to parse {FALLBACK_LANGUAGE}.toml: {error}. \
                 The interface will fall back to translation keys."
            );
            HashMap::new()
        });

        let language = detect_language();
        let messages = if language == FALLBACK_LANGUAGE {
            fallback.clone()
        } else {
            parse_catalog(source(language)).unwrap_or_else(|error| {
                eprintln!(
                    "[ArchSwift] Failed to parse {language}.toml: {error}. \
                     Falling back to English."
                );
                fallback.clone()
            })
        };

        Catalog {
            language,
            messages,
            fallback,
        }
    })
}

/// Returns the embedded catalog for a language code.
fn source(language: &str) -> &'static str {
    catalogs()
        .iter()
        .find(|(code, _)| *code == language)
        .map(|(_, source)| *source)
        // build.rs guarantees that the English catalog exists.
        .unwrap_or_else(|| {
            catalogs()
                .iter()
                .find(|(code, _)| *code == FALLBACK_LANGUAGE)
                .map(|(_, source)| *source)
                .expect("the English catalog must be embedded")
        })
}

fn catalogs() -> &'static [(&'static str, &'static str)] {
    CATALOGS
}

/// Parses TOML and flattens sections into `section.key` keys.
fn parse_catalog(source: &str) -> Result<HashMap<String, String>, toml::de::Error> {
    let table: toml::Table = toml::from_str(source)?;
    let mut messages = HashMap::new();
    flatten_table("", &table, &mut messages);
    Ok(messages)
}

fn flatten_table(prefix: &str, table: &toml::Table, output: &mut HashMap<String, String>) {
    for (key, value) in table {
        let full_key = if prefix.is_empty() {
            key.clone()
        } else {
            format!("{prefix}.{key}")
        };

        match value {
            toml::Value::String(text) => {
                output.insert(full_key, text.clone());
            }
            toml::Value::Table(nested) => flatten_table(&full_key, nested, output),
            _ => {
                // The translation catalog holds only strings; other value types are
                // ignored so that a typo cannot break loading.
            }
        }
    }
}

/// Determines the interface language from the environment.
fn detect_language() -> &'static str {
    // Explicit override: when ARCHSWIFT_LANG is set, system locales are no longer
    // taken into account. An unknown code still yields English rather than a
    // random language from LC_ALL — that keeps testing predictable.
    if let Ok(value) = std::env::var("ARCHSWIFT_LANG") {
        if !value.trim().is_empty() {
            return match_locale(&value).unwrap_or(FALLBACK_LANGUAGE);
        }
    }

    // LANGUAGE is a colon-separated preference list (GNU gettext).
    if let Ok(value) = std::env::var("LANGUAGE") {
        for locale in value.split(':') {
            if let Some(language) = match_locale(locale) {
                return language;
            }
        }
    }

    for variable in ["LC_ALL", "LC_MESSAGES", "LANG"] {
        if let Ok(value) = std::env::var(variable) {
            if !value.is_empty() {
                if let Some(language) = match_locale(&value) {
                    return language;
                }
            }
        }
    }

    FALLBACK_LANGUAGE
}

/// Maps a locale such as `ru_RU.UTF-8` to an embedded catalog code.
///
/// First an exact match with a file code is tried (for example `pt-BR`), then
/// the base language without the region (`pt`), so regional catalogs work as
/// specializations of the general translation.
fn match_locale(locale: &str) -> Option<&'static str> {
    let normalized = locale.trim().to_ascii_lowercase();
    let without_encoding = normalized.split(['.', '@']).next().unwrap_or_default();
    let tag = without_encoding.replace('_', "-");
    let base = tag.split('-').next().unwrap_or_default();

    catalogs()
        .iter()
        .map(|(code, _)| *code)
        .find(|code| code.eq_ignore_ascii_case(&tag))
        .or_else(|| {
            catalogs()
                .iter()
                .map(|(code, _)| *code)
                .find(|code| code.eq_ignore_ascii_case(base))
        })
}

fn interpolate(template: &str, args: &[(&str, &str)]) -> String {
    if args.is_empty() {
        return template.to_string();
    }

    let mut result = template.to_string();
    for (name, value) in args {
        result = result.replace(&format!("{{{name}}}"), value);
    }
    result
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn english_catalog_is_embedded() {
        assert!(
            catalogs()
                .iter()
                .any(|(code, _)| *code == FALLBACK_LANGUAGE),
            "build.rs must embed localization/lang/en.toml"
        );
    }

    #[test]
    fn all_catalogs_have_the_same_keys() {
        let english = parse_catalog(source(FALLBACK_LANGUAGE)).expect("en.toml must be valid TOML");

        for (language, catalog_source) in catalogs() {
            if *language == FALLBACK_LANGUAGE {
                continue;
            }

            let translated = parse_catalog(catalog_source)
                .unwrap_or_else(|_| panic!("{language}.toml is corrupted"));

            let mut missing: Vec<&String> = english
                .keys()
                .filter(|key| !translated.contains_key(*key))
                .collect();
            missing.sort();

            let mut extra: Vec<&String> = translated
                .keys()
                .filter(|key| !english.contains_key(*key))
                .collect();
            extra.sort();

            assert!(
                missing.is_empty(),
                "{language}.toml: missing keys {missing:?}"
            );
            assert!(
                extra.is_empty(),
                "{language}.toml: extra keys without an English original {extra:?}"
            );
        }
    }

    #[test]
    fn interpolation_replaces_named_arguments() {
        assert_eq!(
            interpolate("Пакет {package} готов", &[("package", "demo-1.0-1")]),
            "Пакет demo-1.0-1 готов"
        );
    }

    #[test]
    fn locale_matching_handles_encoding_and_territory() {
        assert_eq!(match_locale("ru_RU.UTF-8"), Some("ru"));
        assert_eq!(match_locale("be_BY.UTF-8"), Some("be"));
        assert_eq!(match_locale("en_US"), Some("en"));
        assert_eq!(match_locale("C"), None);
    }
}
